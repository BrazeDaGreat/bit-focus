export const suggestedProjectIcons = Object.keys(curated);
const resolved = new Map<string, LucideIcon>();
let catalogPromise: Promise<Record<string, LucideIcon>> | undefined;

export function loadProjectIconCatalog() {
  catalogPromise ??= import("./ProjectIconCatalog")
    .then((m) => m.projectIconCatalog)
    .catch((error) => {
      catalogPromise = undefined;
      throw error;
    });
  return catalogPromise;
}

export function humanizeIconName(name: string) {
  return name
    .replace(/([a-z0-9])([A-Z])/g, "$1 $2")
    .replace(/([A-Z])([A-Z][a-z])/g, "$1 $2")
    .replace(/([a-zA-Z])(\d)/g, "$1 $2");
}

export function ProjectIcon({
  name,
  className,
}: {
  name?: string | null;
  className?: string;
}) {
  const [, refresh] = useState(0);
  const Icon = (name && (curated[name] || resolved.get(name))) || Folder;
  useEffect(() => {
    if (!name || curated[name] || resolved.has(name)) return;
    let active = true;
    void loadProjectIconCatalog()
      .then((catalog) => {
        resolved.set(name, catalog[name] || Folder);
        if (active) refresh((value) => value + 1);
      })
      .catch(() => {
        /* Keep the folder fallback if the lazy chunk cannot load. */
      });
    return () => {
      active = false;
    };
  }, [name]);
  return <Icon aria-hidden="true" className={className} />;
}
