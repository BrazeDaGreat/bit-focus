/**
 * Service Worker Precache List
 *
 * Runs after `next build`. Pages only reference the chunks they need on first
 * paint; everything loaded later through `next/dynamic` or `import()` (charts,
 * heatmap, command palette, onboarding, sync helpers) never shows up in a
 * page's HTML. Offline, those imports fail and the page crashes with
 * "Application error: a client-side exception has occurred".
 *
 * This lists every file in `.next/static` and writes `public/sw-precache.js`,
 * which `public/sw.js` loads with `importScripts`. The build id goes in too, so
 * each deploy changes the file, the browser installs the new worker, and the
 * new build's files are cached before the old ones are dropped.
 */

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";

const root = process.cwd();
const nextDir = join(root, ".next");
const staticDir = join(nextDir, "static");
const outFile = join(root, "public", "sw-precache.js");

/** Source maps and dev-only output are never requested by the app. */
const SKIP = /\.map$|(^|\/)development\//;

function walk(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const path = join(dir, entry.name);
    return entry.isDirectory() ? walk(path) : [path];
  });
}

const version = readFileSync(join(nextDir, "BUILD_ID"), "utf8").trim();
const assets = walk(staticDir)
  .map((file) => relative(staticDir, file).split(sep).join("/"))
  .filter((file) => !SKIP.test(file))
  .map((file) => `/_next/static/${file}`)
  .sort();

writeFileSync(
  outFile,
  `// Generated by scripts/generate-sw-precache.mjs. Do not edit.\n` +
    `self.__BITFOCUS_PRECACHE = ${JSON.stringify({ version, assets })};\n`
);

console.log(`sw-precache: ${assets.length} build assets for ${version}`);
